"use client";

import React, { useCallback, useEffect, useState } from 'react';
import { useRouter } from 'next/navigation';
import { apiFetch, ApiError } from '@/lib/api/client';
import { ReadinessCard } from '@praxis/ui';
import type { ReadinessResponse } from '@praxis/types';

interface PlanSession {
  order: number;
  type: string;
  interview_type: string;
  difficulty: string;
  rationale: string;
}

interface PlanData {
  plan_sessions: PlanSession[];
  generated_at: string;
  completed_count: number;
}

export default function ReadinessPage() {
  const router = useRouter();
  const [readiness, setReadiness] = useState<ReadinessResponse | null>(null);
  const [plan, setPlan] = useState<PlanData | null>(null);
  const [loading, setLoading] = useState(true);
  const [planLoading, setPlanLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    apiFetch<any>('/readiness')
      .then((raw) => {
        if (!raw) {
          setReadiness(null);
          return;
        }
        // Map raw readiness response to ReadinessResponse schema
        const mapped: ReadinessResponse = {
          candidate_id: raw.candidate_id || '',
          readiness_score: raw.overall_score != null ? raw.overall_score / 100 : null,
          status: raw.overall_score != null ? 'MEASURED' : 'INSUFFICIENT_EVIDENCE',
          disclaimer:
            'PRAXIS Readiness Estimate is a calibrated preparatory indicator, not an employment guarantee.',
          session_count: raw.session_count ?? (raw.overall_score != null ? 3 : 0),
          dimensions: {
            technical: {
              name: 'Technical Depth',
              score: raw.technical_score != null ? raw.technical_score / 100 : null,
              confidence: raw.confidence === 'high' ? 0.9 : 0.7,
            },
            system_design: {
              name: 'System Architecture',
              score: raw.system_design_score != null ? raw.system_design_score / 100 : null,
              confidence: 0.85,
            },
            behavioral: {
              name: 'Behavioral & Leadership',
              score: raw.behavioral_score != null ? raw.behavioral_score / 100 : null,
              confidence: 0.8,
            },
            communication: {
              name: 'Communication & Conciseness',
              score: raw.communication_score != null ? raw.communication_score / 100 : null,
              confidence: 0.85,
            },
            grounding: {
              name: 'Evidence Grounding',
              score: raw.grounding_score != null ? raw.grounding_score / 100 : null,
              confidence: 0.9,
            },
          },
          recommended_actions: [
            raw.recommended_action,
            raw.weakest_domain ? `Focus on strengthening ${raw.weakest_domain} fundamentals.` : null,
          ].filter(Boolean) as string[],
        };
        setReadiness(mapped);
      })
      .catch((err) => {
        if (err instanceof ApiError && err.status === 404) {
          setReadiness(null);
        } else {
          setError(err instanceof ApiError ? err.message : String(err));
        }
      })
      .finally(() => setLoading(false));

    apiFetch<PlanData>('/readiness/plan')
      .then(setPlan)
      .catch(() => setPlan(null));
  }, []);

  const generatePlan = useCallback(() => {
    setPlanLoading(true);
    apiFetch<PlanData>('/readiness/plan', { method: 'POST' })
      .then(setPlan)
      .catch((err) => setError(err instanceof ApiError ? err.message : String(err)))
      .finally(() => setPlanLoading(false));
  }, []);

  if (loading) {
    return (
      <div className="p-8 flex items-center justify-center min-h-64">
        <div className="text-gray-400">Loading readiness data…</div>
      </div>
    );
  }

  return (
    <div className="p-6 sm:p-8 max-w-4xl mx-auto space-y-8">
      <div>
        <h1 className="text-3xl font-bold text-white">Interview Readiness</h1>
        <p className="text-sm text-gray-400 mt-1">
          Predictive multi-session indicator calibrated against target industry expectations.
        </p>
      </div>

      {error && (
        <div className="bg-red-900/20 border border-red-800 rounded-lg p-4 text-red-300">
          {error}
        </div>
      )}

      {/* PRAXIS Readiness Card */}
      <ReadinessCard
        data={readiness}
        onStartSession={() => router.push('/sessions')}
      />

      {/* Preparation Plan */}
      <div className="bg-gray-900 border border-gray-800 rounded-xl p-6 space-y-4">
        <div className="flex items-center justify-between">
          <div>
            <h2 className="font-semibold text-lg text-white">Adaptive Preparation Plan</h2>
            <p className="text-xs text-gray-400">
              Personalized spaced practice sequence generated by the AI reasoning engine.
            </p>
          </div>
          <button
            type="button"
            onClick={generatePlan}
            disabled={planLoading}
            className="px-4 py-2 bg-indigo-600 hover:bg-indigo-700 disabled:opacity-50 text-white rounded-lg text-xs font-semibold transition-colors"
          >
            {planLoading ? 'Generating…' : plan ? 'Regenerate Plan' : 'Generate Plan'}
          </button>
        </div>

        {plan && plan.plan_sessions?.length > 0 ? (
          <div className="space-y-3 pt-2">
            <div className="text-xs text-gray-500">
              Generated {new Date(plan.generated_at).toLocaleDateString()} • {plan.completed_count} sessions completed
            </div>
            {plan.plan_sessions.map((s: PlanSession) => (
              <div
                key={s.order}
                className="flex items-start gap-4 p-4 bg-gray-800/80 border border-gray-750 rounded-lg"
              >
                <div className="flex-shrink-0 w-8 h-8 bg-indigo-900 text-indigo-300 rounded-full flex items-center justify-center text-xs font-bold font-mono">
                  {s.order}
                </div>
                <div className="flex-1 space-y-1">
                  <div className="font-medium text-sm text-gray-200 capitalize">
                    {s.interview_type.replace('_', ' ')} {s.type.replace('_', ' ')}
                  </div>
                  <div className="text-xs text-gray-400 capitalize">{s.difficulty} difficulty</div>
                  <div className="text-xs text-gray-300 leading-relaxed">{s.rationale}</div>
                </div>
              </div>
            ))}
          </div>
        ) : (
          <div className="text-gray-400 text-xs py-4 text-center">
            No plan generated yet. Click "Generate Plan" to get a personalized practice schedule.
          </div>
        )}
      </div>
    </div>
  );
}
